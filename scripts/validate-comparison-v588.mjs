import fs from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('/opt/nvm/versions/node/v22.16.0/lib/node_modules/typescript/lib/typescript.js');

const cmpSource = fs.readFileSync(new URL('../src/utils/comparison.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(cmpSource, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, verbatimModuleSyntax: false }, fileName: 'comparison.ts' }).outputText;
const mod = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const index = fs.readFileSync(new URL('../src/routes/index.tsx', import.meta.url), 'utf8');
const card = fs.readFileSync(new URL('../src/components/KpiCard.tsx', import.meta.url), 'utf8');
const service = fs.readFileSync(new URL('../src/services/liveDashboardService.ts', import.meta.url), 'utf8');
const types = fs.readFileSync(new URL('../src/types/live.ts', import.meta.url), 'utf8');
const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

const checks=[];
const check=(cond,label)=>{ if(!cond) throw new Error(`FAIL: ${label}`); checks.push(label); };
check(pkg.version==='5.8.9','versão frontend 5.8.9');
check(mod.getComparisonLabel('24h')==='vs ontem','rótulo 24h hoje vs ontem');
check(mod.getComparisonLabel('7d')==='vs 7 dias anteriores','rótulo 7d transparente');
check(mod.getComparisonLabel('30d')==='vs 30 dias anteriores','rótulo 30d transparente');
check(mod.percentageChange(10,2,5)===null,'base anterior abaixo de 5 é rejeitada');
check(Math.abs(mod.percentageChange(11,10,5)-10)<1e-9,'percentual válido preservado');
check(Math.abs(mod.utilizationChangePp(1.2,0.8,2)-20)<1e-9,'utilização em pontos percentuais');
check(index.includes('minimumCoveragePct = 70'),'cobertura mínima 70%');
check(index.includes('minimumOperationalSamples = 6'),'mínimo de amostras operacionais');
check(index.includes('percentageChange(comparison?.current.avgKw, comparison?.previous.avgKw, 5)'),'base mínima potência 5kW');
check(index.includes('percentageChange(comparison?.current.avgTr, comparison?.previous.avgTr, 5)'),'base mínima produção 5TR');
check(index.includes('percentageChange(comparison?.current.avgAuxKw, comparison?.previous.avgAuxKw, 5)'),'base mínima periféricos 5kW');
check(index.includes('utilizationChangePp'),'chillers usa p.p.');
check(index.includes('comparisonUnit="p.p."'),'UI chillers mostra p.p.');
check(index.includes('média em operação'),'UI explicita média em operação');
check(index.includes('eficiência do período'),'UI explicita eficiência do período');
check(!index.includes('comparisonTone="lower-better"\n        />\n        <KpiCard\n          icon={Thermometer}'),'periféricos não tratados como menor-sempre-melhor');
check(card.includes('comparisonDescription?: string'),'tooltip semântico por KPI');
check(card.includes('comparisonUnit === "p.p."'),'formatação p.p.');
check(service.includes('coveragePct: asNumber(input?.coveragePct)'),'normalização coveragePct');
check(service.includes('operationalSampleCount: asNumber(input?.operationalSampleCount)'),'normalização amostras operacionais');
check(types.includes('efficiencyThermalTrh: number | null'),'tipo base térmica da eficiência');
console.log(`PASS ${checks.length}/${checks.length}`);
for (const x of checks) console.log(`- ${x}`);
